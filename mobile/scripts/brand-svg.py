# Generates the Fut Career logo files (16 Oct 2026 decision): the football mark
# on the lime square with the FUTCAREER wordmark — white FUT and lime CAREER on
# dark surfaces, all black on light surfaces.
#
#   python3 scripts/app-icon-svg.py assets/brand/app-icon.svg    (the football master)
#   python3 scripts/brand-svg.py <BarlowCondensed-ExtraBoldItalic.ttf>
#   sh scripts/app-icon.sh                                         (PNG icons, launch logo)
#
# Writes:
#   assets/brand/logo-mark.svg                   the mark (rounded square, flat lime)
#   assets/brand/logo-lockup-{light,dark}.svg    mark + wordmark for light / dark surfaces
#   src/shared/ui/brand-paths.ts                 wordmark outlines for Wordmark.tsx
#   ../frontend/src/shared/ui/brand-paths.ts     same outlines for the admin panel
#   ../frontend/src/shared/ui/brand-mark.svg     the mark for the admin panel
# The wordmark is Barlow Condensed ExtraBold Italic (SIL OFL 1.1) converted to
# outlines, so no font file ships with the apps.
import os, re, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIME, LIME_INK, WHITE = "#B6F36A", "#0B1206", "#F4F7FA"
# surface -> ("FUT", "CAREER") colours
WORDMARK = {"light": (LIME_INK, LIME_INK), "dark": (WHITE, LIME)}
RADIUS = 1024 * 16 / 72  # same corner as the in-app LogoMark


def ball_icon():
    """The app icon master (football on lime) with a flat lime square, so the
    logo matches the in-app mark drawn from tokens."""
    with open(os.path.join(ROOT, "assets/brand/app-icon.svg")) as source:
        svg = source.read()
    if "<polygon" not in svg:
        sys.exit("assets/brand/app-icon.svg is not the football; run scripts/app-icon-svg.py first")
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = svg.replace('fill="url(#field)"', 'fill="%s"' % LIME)
    return svg[svg.index(">") + 1 : svg.rindex("</svg>")]


def mark_svg(size, prefix="m"):
    # Prefix ids so several marks can share one document.
    inner = re.sub(r'id="([^"]+)"', r'id="%s-\1"' % prefix, ball_icon())
    inner = re.sub(r"url\(#([^)]+)\)", r"url(#%s-\1)" % prefix, inner)
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="%d" height="%d">'
        '<defs><clipPath id="%s-corner"><rect width="1024" height="1024" rx="%.1f"/></clipPath></defs>'
        '<g clip-path="url(#%s-corner)">%s</g></svg>'
    ) % (size, size, prefix, RADIUS, prefix, inner)


def wordmark(font_path, text="FUTCAREER", split=3, height=100.0):
    """Outlines of the wordmark scaled so cap height == height; returns
    (width, height, [path for text[:split], path for text[split:]])."""
    font = TTFont(font_path)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = height / font["OS/2"].sCapHeight
    parts, x = [[], []], 0.0
    for index, char in enumerate(text):
        name = cmap[ord(char)]
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x * scale, height)))
        parts[0 if index < split else 1].append(pen.getCommands())
        x += glyphs[name].width
    # Italic overhang: the last letter leans right past its advance.
    width = x * scale + height * 0.12
    return round(width, 1), height, [" ".join(p) for p in parts]


def lockup_svg(variant, word):
    width, height, (fut, career) = word
    fut_colour, career_colour = WORDMARK[variant]
    mark, gap = 140.0, 36.0  # mark edge and gap next to a 100-unit cap height
    inner = mark_svg(1024, "lockup")
    inner = inner[inner.index(">") + 1 : inner.rindex("</svg>")]
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %.1f %.1f">'
        '<g transform="scale(%.5f)">%s</g>'
        '<g transform="translate(%.1f %.1f)"><path d="%s" fill="%s"/><path d="%s" fill="%s"/></g></svg>'
    ) % (mark + gap + width, mark, mark / 1024, inner, mark + gap, (mark - height) / 2,
         fut, fut_colour, career, career_colour)


def ts_module(word):
    width, height, (fut, career) = word
    return (
        "// Generated by mobile/scripts/brand-svg.py; do not edit by hand.\n"
        "// FUTCAREER wordmark outlines (Barlow Condensed ExtraBold Italic, SIL OFL 1.1).\n"
        "export const wordmarkSize = { width: %s, height: %s };\n"
        "export const wordmarkFut = '%s';\n"
        "export const wordmarkCareer = '%s';\n"
    ) % (width, height, fut, career)


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w") as out:
        out.write(text)
    print("wrote", path)


def main():
    word = wordmark(sys.argv[1])
    write("assets/brand/logo-mark.svg", mark_svg(512))
    for variant in WORDMARK:
        write("assets/brand/logo-lockup-%s.svg" % variant, lockup_svg(variant, word))
    module = ts_module(word)
    write("src/shared/ui/brand-paths.ts", module)
    write("../frontend/src/shared/ui/brand-paths.ts", module)
    write("../frontend/src/shared/ui/brand-mark.svg", mark_svg(72))


if __name__ == "__main__":
    main()
